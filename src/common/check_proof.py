def snapshot_worktree(filepath):
    """Capture the worktree as a git tree object via a throwaway index.

    Best-effort: returns (repo_root, tree_sha), or (None, None) on any failure —
    tracking must never affect the check itself.
    """
    try:
        repo_root = _git_root(filepath)
        if not repo_root:
            return None, None
        cache = os.path.relpath(os.path.join(os.path.dirname(os.path.abspath(filepath)), ".tlacache"), repo_root)
        with tempfile.TemporaryDirectory(prefix="tlaps_snap_") as d:
            env = {**os.environ, "GIT_INDEX_FILE": os.path.join(d, "index")}
            add = subprocess.run(
                ["git", "add", "-A", "--", ".", f":(exclude){cache}"],
                capture_output=True,
                text=True,
                cwd=repo_root,
                env=env,
            )
            if add.returncode != 0:
                return None, None
            wt = subprocess.run(["git", "write-tree"], capture_output=True, text=True, cwd=repo_root, env=env)
            tree = wt.stdout.strip()
            return (repo_root, tree) if wt.returncode == 0 and tree else (None, None)
    except Exception:
        return None, None


def record_check_commit(repo_root, tree, message):
    """Append the snapshot to GIT_TRACK_REF. Best-effort: commit sha or None."""
    try:
        tip = subprocess.run(
            ["git", "rev-parse", "--verify", "--quiet", GIT_TRACK_REF],
            capture_output=True,
            text=True,
            cwd=repo_root,
        ).stdout.strip()
        cmd = ["git", "commit-tree", "-m", message] + (["-p", tip] if tip else []) + [tree]
        ct = subprocess.run(cmd, capture_output=True, text=True, cwd=repo_root, env={**os.environ, **_GIT_ID})
        commit = ct.stdout.strip()
        if ct.returncode != 0 or not commit:
            return None
        ur = subprocess.run(["git", "update-ref", GIT_TRACK_REF, commit], capture_output=True, text=True, cwd=repo_root)
        return commit if ur.returncode == 0 else None
    except Exception:
        return None


