# --- Sharded verification --------------------------------------------------
# A huge proof is split into contiguous line ranges cut at top-level unit
# heads and verified as parallel `tlapm --strict --toolbox <s> <e>` runs.
# Sound because tlapm attributes every obligation and missing step to exactly
# one line and its toolbox-range reporting is range-filtered, so over a
# partition of [1, EOF] the per-shard results compose to the module verdict.

SHARD_MIN_LINES = 5000  # auto-sharding activates above this ($TLAPS_SHARD_MIN_LINES)
SHARD_MEM_MB = 4096  # assumed per-shard peak RSS for the auto cap ($TLAPS_SHARD_MEM_MB)

_UNIT_HEAD_RE = re.compile(r"[ \t]*(THEOREM|LEMMA|COROLLARY|PROPOSITION)\b")


def regex_unit_heads(text):
    """1-indexed lines starting a THEOREM/LEMMA/COROLLARY/PROPOSITION, with
    comments stripped line-preservingly so a keyword inside one never counts."""
    text = re.sub(r"\(\*.*?\*\)", lambda m: "\n" * m.group(0).count("\n"), text, flags=re.DOTALL)
    text = re.sub(r"\\\*.*", "", text)
    return [i for i, line in enumerate(text.split("\n"), 1) if _UNIT_HEAD_RE.match(line)]


def unit_head_lines(filepath):
    """Start lines of top-level proof units: SANY-exact, regex fallback."""
    try:
        from tlacore.sany.dump import dump_normalized

        mod = dump_normalized(filepath, dep_dir=os.path.dirname(os.path.abspath(filepath)), timeout=120)
        heads = sorted({t.loc.line_start for t in mod.theorems if t.loc and t.loc.line_start > 0})
        if heads:
            return heads
    except Exception:
        pass
    try:
        with open(filepath) as f:
            return regex_unit_heads(f.read())
    except OSError:
        return []


def _available_mem_mb():
    try:
        with open("/proc/meminfo") as f:
            for line in f:
                if line.startswith("MemAvailable:"):
                    return int(line.split()[1]) // 1024
    except (OSError, ValueError, IndexError):
        pass
    return None


def auto_shard_count(n_units):
    """~nproc/2 (tangruize's guidance), capped by available memory at an
    assumed per-shard RSS budget, never more than there are units to split."""
    n = max(1, (os.cpu_count() or 2) // 2)
    mem = _available_mem_mb()
    if mem:
        try:
            per_shard = int(os.environ.get("TLAPS_SHARD_MEM_MB", SHARD_MEM_MB))
        except ValueError:
            per_shard = SHARD_MEM_MB
        n = min(n, max(1, mem // max(1, per_shard)))
    return max(1, min(n, n_units))


def plan_shards(total_lines, unit_heads, n_shards):
    """Contiguous ranges partitioning [1, total_lines], every boundary sitting
    on a unit head line, balanced by line span. Fewer heads clamp the count."""
    cuts = sorted({h for h in unit_heads if 1 < h <= total_lines})
    n = max(1, min(n_shards, len(cuts) + 1))
    chosen, lo = [], 0
    for k in range(1, n):
        ideal = 1 + k * total_lines // n
        hi = len(cuts) - (n - 1 - k)  # keep enough cuts for later boundaries
        i = bisect.bisect_left(cuts, ideal, lo, hi)
        best = min((j for j in (i - 1, i) if lo <= j < hi), key=lambda j: abs(cuts[j] - ideal))
        chosen.append(cuts[best])
        lo = best + 1
    return list(zip([1] + chosen, [c - 1 for c in chosen] + [total_lines], strict=True))


_SHARD_FAILED_RE = re.compile(r"(\d+)/(\d+) obligations? failed\.")
_SHARD_PROVED_RE = re.compile(r"All (\d+) obligations? proved\.")
_SHARD_INCOMPLETE_RE = re.compile(r"Proof incomplete in module .*?:\s*(\d+) missing, (\d+) omitted")


def compose_shard_results(results, module_name, timeout):
    """Compose per-shard ``(start, end, rc, output)`` into one module-level
    ``(tlapm_output, tlapm_exit)`` equivalent to a single full-file run.

    Per-shard canonical summary lines are consumed into module totals and the
    composed output ends with ONE synthesized canonical summary, so
    parse_strict_status and every downstream regex read module-wide numbers.
    A shard rc of None means timeout; unexpected rcs propagate (never PASS).
    """
    total = failed = missing = omitted = 0
    parts, timed_out = [], []
    for i, (s, e, rc, out) in enumerate(results, 1):
        parts.append(f"--- shard {i}/{len(results)}: lines {s}-{e} (exit {rc}) ---")
        in_record = False
        for line in out.split("\n"):
            if line.startswith("@!!BEGIN"):
                in_record = True
                continue
            if line.startswith("@!!END"):
                in_record = False
                continue
            if in_record or line.startswith("@!!") or line.startswith("\\*"):
                continue
            m = _SHARD_FAILED_RE.search(line)
            if m:
                failed += int(m.group(1))
                total += int(m.group(2))
                continue
            m = _SHARD_PROVED_RE.search(line)
            if m:
                total += int(m.group(1))
                continue
            m = _SHARD_INCOMPLETE_RE.search(line)
            if m:
                missing += int(m.group(1))
                omitted += int(m.group(2))
                continue
            if line.strip():
                parts.append(line)
        if rc is None:
            timed_out.append((i, s, e))

    rcs = [rc for _s, _e, rc, _o in results]
    if timed_out:
        for i, s, e in timed_out:
            parts.append(f"TIMEOUT after {timeout}s (shard {i}: lines {s}-{e})")
        return "\n".join(parts), -1
    unexpected = [rc for rc in rcs if rc not in (0, 10, 11, 12)]
    if unexpected:
        exit_code = unexpected[0]
    elif 10 in rcs:
        exit_code = 10
    elif 11 in rcs:
        exit_code = 11
    elif all(rc == 12 for rc in rcs):
        exit_code = 12
    else:
        exit_code = 0

    parts.append(f"=== module summary (composed from {len(results)} shards) ===")
    plural = "" if total == 1 else "s"
    if failed:
        parts.append(f"[ERROR]: {failed}/{total} obligation{plural} failed.")
    else:
        parts.append(f"[INFO]: All {total} obligation{plural} proved.")
    if missing or omitted:
        parts.append(
            f'[ERROR]: Proof incomplete in module "{module_name}": {missing} missing, {omitted} omitted proof step(s).'
        )
    return "\n".join(parts), exit_code


def run_sharded_tlapm(tlapm_path, tlapm_lib, community_lib, tmp_file, ranges, cache_root, timeout, tmp_dir):
    """One `tlapm --strict --toolbox s e` per range, all in parallel under the
    same wall-clock deadline. Per-shard cache dirs are mandatory: parallel
    writers to one cache dir clobber each other's fingerprints."""

    def one(item):
        i, (s, e) = item
        cmd = [tlapm_path, "--strict", "--toolbox", str(s), str(e), "--threads", "1", "-I", tlapm_lib]
        if community_lib:
            cmd += ["-I", community_lib]
        shard_cache = os.path.join(cache_root, f"shard-{i}")
        os.makedirs(shard_cache, exist_ok=True)  # tlapm mkdirs only one level
        cmd += ["--cache-dir", shard_cache, "--safefp", tmp_file]
        try:
            out, err, rc = run_killgroup(cmd, effective_timeout(timeout), tmp_dir)
            return (s, e, rc, out + err)
        except subprocess.TimeoutExpired:
            return (s, e, None, "")
        except Exception as exc:
            return (s, e, -2, f"ERROR: {exc}")

    with ThreadPoolExecutor(max_workers=len(ranges)) as pool:
        return list(pool.map(one, enumerate(ranges)))


