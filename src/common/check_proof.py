def _module_context_issues(filepath: str, benchmark_dir: str) -> list[tuple[str, str]]:
    """Compare supplied TLA+ dependencies with the frozen canonical copy.

    Extra workspace modules are development artifacts, not submitted context.
    Canonical replay never stages them, and the module contract independently
    rejects a final task that imports an unapproved module.
    """

    target_name = os.path.basename(filepath)
    workspace = os.path.dirname(filepath)
    canonical_paths = {
        os.path.basename(path): path for path in glob.glob(os.path.join(benchmark_dir, "*.tla")) if os.path.isfile(path)
    }
    workspace_paths = {
        os.path.basename(path): path
        for path in glob.glob(os.path.join(workspace, "*.tla"))
        if os.path.isfile(path) or os.path.islink(path)
    }
    issues: list[tuple[str, str]] = []
    expected_context = set(canonical_paths) - {target_name}
    actual_context = set(workspace_paths) - {target_name}
    for missing in sorted(expected_context - actual_context):
        issues.append(("CONTEXT_MISSING", f"canonical context file {missing!r} is missing from the submission"))
    for name in sorted(expected_context & actual_context):
        submitted = workspace_paths[name]
        if os.path.islink(submitted):
            issues.append(("CONTEXT_MODIFIED", f"context file {name!r} was replaced by a symlink"))
            continue
        try:
            if os.path.samefile(submitted, canonical_paths[name]):
                issues.append(("CONTEXT_MODIFIED", f"context file {name!r} aliases the canonical input"))
                continue
        except OSError as exc:
            issues.append(("CONTEXT_MODIFIED", f"cannot compare context file {name!r}: {exc}"))
            continue
        try:
            with open(canonical_paths[name], "rb") as expected_stream:
                expected = expected_stream.read()
            with open(submitted, "rb") as submitted_stream:
                actual = submitted_stream.read()
        except OSError as exc:
            issues.append(("CONTEXT_MODIFIED", f"cannot compare context file {name!r}: {exc}"))
            continue
        if actual != expected:
            issues.append(("CONTEXT_MODIFIED", f"context file {name!r} differs from the canonical input"))
    return issues


def _module_unit_result(
    *,
    unit,
    tlapm_path: str,
    tlapm_lib: str,
    community_lib: str | None,
    staged_file: str,
    tmp_dir: str,
    deadline: float | None,
    index: int,
) -> tuple[dict[str, object], str]:
    base = {
        "unit_id": unit.unit_id,
        "kind": unit.kind,
        "theorem_name": unit.theorem_name,
        "line_start": unit.line_start,
        "line_end": unit.line_end,
        "dependencies": list(unit.dependencies),
    }
    if unit.admitted:
        return (
            {
                **base,
                "raw_verdict": "UNRESOLVED",
                "tlapm_exit": None,
                "missing_proofs": 1,
                "obligation_failed": False,
                "obligations": 0,
            },
            "proof is omitted or missing",
        )
    if unit.line_start <= 0 or unit.line_end < unit.line_start:
        return (
            {
                **base,
                "raw_verdict": "ERROR",
                "tlapm_exit": None,
                "missing_proofs": None,
                "obligation_failed": None,
                "obligations": None,
            },
            "SANY did not provide a valid theorem location",
        )

    remaining = None if deadline is None else deadline - time.monotonic()
    if remaining is not None and remaining <= 0:
        return (
            {
                **base,
                "raw_verdict": "TIMEOUT",
                "tlapm_exit": None,
                "missing_proofs": None,
                "obligation_failed": None,
                "obligations": None,
            },
            "module checker timeout exhausted before this proof unit",
        )

    command = [
        tlapm_path,
        "--strict",
        "--toolbox",
        str(unit.line_start),
        str(unit.line_end),
        "--threads",
        "1",
        "-I",
        tlapm_lib,
    ]
    if community_lib:
        command += ["-I", community_lib]
    cache_dir = os.path.join(tmp_dir, "unit-cache", str(index))
    os.makedirs(cache_dir, exist_ok=True)
    command += ["--cache-dir", cache_dir, "--safefp", staged_file]
    try:
        stdout, stderr, returncode = run_killgroup(command, remaining, tmp_dir)
    except subprocess.TimeoutExpired:
        return (
            {
                **base,
                "raw_verdict": "TIMEOUT",
                "tlapm_exit": None,
                "missing_proofs": None,
                "obligation_failed": None,
                "obligations": None,
            },
            "TLAPM timed out",
        )
    except Exception as exc:
        return (
            {
                **base,
                "raw_verdict": "ERROR",
                "tlapm_exit": None,
                "missing_proofs": None,
                "obligation_failed": None,
                "obligations": None,
            },
            f"TLAPM could not run: {exc}",
        )

    output = stdout + stderr
    complete, missing, obligation_failed = parse_strict_status(returncode, output)
    # This TLAPM invocation is scoped to exactly one submitted target/helper.
    # Exit 11 therefore means that unit still contains an omitted or missing
    # proof; admitted siblings outside the toolbox range do not affect it.
    complete = complete and returncode == 0
    return (
        {
            **base,
            "raw_verdict": "PASS" if complete else "FAIL",
            "tlapm_exit": returncode,
            "missing_proofs": missing,
            "obligation_failed": obligation_failed,
            "obligations": _module_obligation_count(output),
        },
        output,
    )


def run_module_task_check(
    *,
    filepath: str,
    benchmark_dir: str,
    expected_unit_ids: tuple[str, ...],
    tlapm_path: str,
    tlapm_lib: str,
    timeout: int,
    output_path: str,
    import_violations: list,
    emit,
) -> int:
    """Grade one complete submitted module and emit per-unit trust evidence."""

    deadline = None if timeout <= 0 else time.monotonic() + timeout
    canonical_path = os.path.join(benchmark_dir, os.path.basename(filepath))
    try:
        with open(canonical_path, encoding="utf-8", newline="") as stream:
            canonical_source = stream.read()
        with open(filepath, encoding="utf-8", newline="") as stream:
            submitted_source = stream.read()
    except (OSError, UnicodeError) as exc:
        emit("SANY-STATUS: unavailable")
        emit(f"ERROR: cannot read module task inputs: {exc}")
        return 3

    integrity_issues = _module_context_issues(filepath, benchmark_dir)
    integrity_issues.extend((violation.code, violation.message) for violation in import_violations)
    tmp_dir = tempfile.mkdtemp(prefix="tlaps_module_check_")
    try:
        try:
            staged_file = stage_verification_files(
                filepath,
                tmp_dir,
                benchmark_dir=benchmark_dir,
                require_canonical=True,
            )
        except (OSError, ValueError) as exc:
            emit("SANY-STATUS: unavailable")
            emit(f"ERROR: cannot stage module task inputs: {exc}")
            return 3

        remaining = None if deadline is None else deadline - time.monotonic()
        if remaining is not None and remaining <= 0:
            emit("SANY-STATUS: unavailable")
            emit("CHECK-TIMEOUT: module checker budget exhausted before SANY validation")
            emit("ERROR: module checker timeout exhausted before SANY validation")
            return 3
        sany_timeout = 180 if remaining is None else max(1, min(180, math.ceil(remaining)))
        sany_run = run_normalized(staged_file, dep_dir=tmp_dir, timeout=sany_timeout)
        try:
            write_sany_log(sany_run, output_path)
        except OSError as exc:
            emit("SANY-STATUS: unavailable")
            emit(f"ERROR: cannot write SANY log: {exc}")
            return 3
        emit(f"SANY-STATUS: {sany_run.status.value}")
        if sany_run.status is SanyStatus.UNAVAILABLE:
            if sany_run.returncode is None and "timed out" in sany_run.detail:
                emit(f"CHECK-TIMEOUT: {sany_run.detail[:300]}")
            emit(f"ERROR: SANY validation unavailable: {sany_run.detail[:300]}")
            return 3
        if sany_run.status is SanyStatus.INVALID:
            report = {
                "schema_version": MODULE_RESULT_SCHEMA_VERSION,
                "sany_status": "invalid",
                "proof_unit_ids": list(expected_unit_ids),
                "units": [],
                "trusted_unit_ids": [],
                "trusted_proof_unit_ids": [],
                "complete": False,
            }
            emit(MODULE_RESULT_PREFIX + json.dumps(report, sort_keys=True, separators=(",", ":")))
            emit(f"FAIL {SANY_INVALID_MARKER} — {sany_run.detail[:300]}")
            return 1

        assert sany_run.raw is not None
        remaining = None if deadline is None else deadline - time.monotonic()
        if remaining is not None and remaining <= 0:
            emit("CHECK-TIMEOUT: module checker budget exhausted before canonical SANY validation")
            emit("ERROR: module checker timeout exhausted before canonical SANY validation")
            return 3
        canonical_sany_timeout = 180 if remaining is None else max(1, min(180, math.ceil(remaining)))
        canonical_sany_run = run_normalized(
            canonical_path,
            dep_dir=benchmark_dir,
            timeout=canonical_sany_timeout,
        )
        if canonical_sany_run.status is not SanyStatus.VALID or canonical_sany_run.raw is None:
            if canonical_sany_run.returncode is None and "timed out" in canonical_sany_run.detail:
                emit(f"CHECK-TIMEOUT: {canonical_sany_run.detail[:300]}")
            emit(f"ERROR: canonical module SANY validation unavailable: {canonical_sany_run.detail[:300]}")
            return 3
        canonical_module = Module.parse(canonical_sany_run.raw)
        try:
            analysis = analyze_module_submission(
                canonical_source=canonical_source,
                submitted_source=submitted_source,
                expected_unit_ids=expected_unit_ids,
                module=Module.parse(sany_run.raw),
                expected_extends=canonical_module.extends,
            )
        except ModuleSubmissionError as exc:
            integrity_issues.append((exc.code, str(exc)))

        if integrity_issues:
            report = {
                "schema_version": MODULE_RESULT_SCHEMA_VERSION,
                "sany_status": "valid",
                "proof_unit_ids": list(expected_unit_ids),
                "units": [],
                "trusted_unit_ids": [],
                "trusted_proof_unit_ids": [],
                "complete": False,
                "integrity_issues": [{"code": code, "message": message} for code, message in integrity_issues],
            }
            emit(MODULE_RESULT_PREFIX + json.dumps(report, sort_keys=True, separators=(",", ":")))
            for code, message in integrity_issues:
                emit(f"FAIL {code}: {message}")
            emit("GATES-FAILED: module_integrity")
            cheat_codes = sorted(
                {code for code, _message in integrity_issues if code not in _NON_CHEAT_MODULE_INTEGRITY_CODES}
            )
            if cheat_codes:
                emit("CHEAT-DETECTED: " + ",".join(cheat_codes))
            return 1

        unit_results: list[dict[str, object]] = []
        community_lib = find_community_lib(filepath)
        for index, unit in enumerate(analysis.checked_units):
            unit_result, raw_output = _module_unit_result(
                unit=unit,
                tlapm_path=tlapm_path,
                tlapm_lib=tlapm_lib,
                community_lib=community_lib,
                staged_file=staged_file,
                tmp_dir=tmp_dir,
                deadline=deadline,
                index=index,
            )
            unit_results.append(unit_result)
            emit("-" * 60)
            emit(f"PROOF UNIT {unit.unit_id}: {unit_result['raw_verdict']}")
            for line in raw_output.splitlines():
                emit(line)

        raw_pass = {result["unit_id"] for result in unit_results if result["raw_verdict"] == "PASS"}
        trusted = compute_trusted_units(raw_pass, analysis.local_dependencies)
        trusted_targets = [unit.unit_id for unit in analysis.target_units if unit.unit_id in trusted]
        for result in unit_results:
            result["trusted"] = result["unit_id"] in trusted
        complete = len(trusted_targets) == len(expected_unit_ids)
        report = {
            "schema_version": MODULE_RESULT_SCHEMA_VERSION,
            "sany_status": "valid",
            "proof_unit_ids": list(expected_unit_ids),
            "units": unit_results,
            "trusted_unit_ids": sorted(trusted),
            "trusted_proof_unit_ids": trusted_targets,
            "unused_helper_names": list(analysis.unused_helper_names),
            "complete": complete,
        }
        emit(MODULE_RESULT_PREFIX + json.dumps(report, sort_keys=True, separators=(",", ":")))

        unavailable = any(result["raw_verdict"] in {"ERROR", "TIMEOUT"} for result in unit_results)
        if unavailable:
            emit("ERROR: one or more proof-unit checks were unavailable")
            return 3
        if complete:
            emit(
                f"PASS — {len(trusted_targets)}/{len(expected_unit_ids)} proof units are dependency-closed and trusted"
            )
            return 0
        emit(f"FAIL — {len(trusted_targets)}/{len(expected_unit_ids)} proof units are dependency-closed and trusted")
        return 1
    finally:
        shutil.rmtree(tmp_dir, ignore_errors=True)


def _run_in_container(filepath, args):
    """Run check_proof_bin inside Docker container."""
    require_canonical = getattr(args, "canonical_replay_required", False) and not args.sany_only
    target_name = os.path.splitext(os.path.basename(filepath))[0]
    benchmark_dir = None if args.sany_only else args.benchmark_dir or resolve_benchmark_dir(None, filepath, target_name)
    if require_canonical:
        benchmark_dir = resolve_benchmark_dir(benchmark_dir, filepath, target_name)
    if require_canonical and benchmark_dir is None:
        print("ERROR: canonical replay required, but no canonical benchmark directory is available")
        sys.exit(3)
    if benchmark_dir is not None:
        try:
            require_independent_canonical_target(filepath, benchmark_dir)
        except RuntimeError as exc:
            print(f"ERROR: {exc}")
            sys.exit(3)

    try:
        container_image = ensure_image(force=getattr(args, "force_build", False))
    except DockerUnavailableError as e:
        print(f"ERROR: {e}", file=sys.stderr)
        sys.exit(3)
    runner = ContainerRunner()

    # Mount repo root so git cheating checks (main branch comparison) work
    repo_root = subprocess.run(
        ["git", "rev-parse", "--show-toplevel"],
        capture_output=True,
        text=True,
        cwd=os.path.dirname(filepath) or ".",
    ).stdout.strip()

    result_dir = tempfile.mkdtemp(prefix="tlaps_check_docker_")

    if repo_root:
        rel_path = os.path.relpath(filepath, repo_root)
        container_file = f"/workspace/{rel_path}"
        workspace = repo_root
    else:
        container_file = f"/workspace/{os.path.basename(filepath)}"
        workspace = os.path.dirname(filepath)

    cmd = ["/usr/local/bin/check_proof_bin", container_file]
    cmd += ["--no-container"]
    cmd += ["--mode", args.mode]
    cmd += ["--timeout", str(args.timeout)]
    cmd += ["--output", "/results/check.result"]
    if benchmark_dir:
        # Mount the canonical dir read-only at /benchmark; pointing the checker
        # at the workspace instead would make the baseline oracle the solution
        # itself, silently passing tamper checks.
        cmd += ["--benchmark-dir", "/benchmark"]
    if require_canonical:
        cmd += ["--canonical-replay-required"]
    if args.sany_only:
        cmd += ["--sany-only"]
    if args.no_cache:
        cmd += ["--no-cache"]
    if args.keep_verifying:
        cmd += ["--keep-verifying"]
    if args.no_git_track:
        cmd += ["--no-git-track"]
    if args.shards is not None:
        cmd += ["--shards", str(args.shards)]

    config = ContainerConfig(
        image=container_image,
        workspace=workspace,
        result_dir=result_dir,
        benchmark_dir=os.path.abspath(benchmark_dir) if benchmark_dir else "",
    )
    config.env["GIT_CONFIG_COUNT"] = "1"
    config.env["GIT_CONFIG_KEY_0"] = "safe.directory"
    config.env["GIT_CONFIG_VALUE_0"] = "/workspace"
    # Keep --timeout 0 unbounded in the outer Docker call too.
    container_timeout = args.timeout + 60 if args.timeout > 0 else None
    try:
        exit_code, stdout, stderr = runner.run_with_output(config, cmd, timeout=container_timeout)
        # Print output, filtering container-internal paths
        if stdout:
            for line in stdout.splitlines():
                if line.startswith("Result written to: /results/"):
                    continue
                print(line)
        if stderr:
            print(stderr, end="", file=sys.stderr)

        # Copy checker artifacts from the temporary container result mount before
        # it is removed. --sany-only writes only the SANY log, so keep the copies
        # independent instead of nesting the log copy under check.result.
        container_result = os.path.join(result_dir, "check.result")
        container_sany_log = os.path.join(result_dir, "sany.log")
        output_path = args.output or (os.path.splitext(filepath)[0] + ".result")
        if os.path.isfile(container_result):
            shutil.copy2(container_result, output_path)
            print(f"\nResult written to: {output_path}")
        if os.path.isfile(container_sany_log):
            shutil.copy2(container_sany_log, sany_log_path(output_path))

        sys.exit(exit_code)
    finally:
        shutil.rmtree(result_dir, ignore_errors=True)


def main(*, require_canonical_for_proof_from_scratch: bool = False):
    parser = argparse.ArgumentParser(description="Check a single TLAPS benchmark proof")
    parser.add_argument("file", help="Path to the benchmark .tla file")
    parser.add_argument(
        "--mode",
        default="proof-completion",
        choices=["proof-completion", "proof-from-scratch"],
        help="Benchmark mode — controls cheating rules (default: proof-completion)",
    )
    parser.add_argument("--tlapm", default=None, help="Path to tlapm binary")
    parser.add_argument("--tlapm-lib", default=None, help="Path to tlapm lib directory")
    parser.add_argument(
        "--timeout",
        type=int,
        default=None,
        help="Timeout in seconds; 0 means no limit. If omitted, uses $TLAPS_CHECK_TIMEOUT (set by the "
        "runner so the agent's self-check uses the SAME tlapm budget as the grader), "
        "else 600.",
    )
    parser.add_argument(
        "--no-cache",
        action="store_true",
        help="Verify from scratch: do not reuse or write the target-side .tlacache.",
    )
    parser.add_argument(
        "--keep-verifying",
        action="store_true",
        help="Run tlapm even when cheating is detected (default: fail fast, skipping the proving run).",
    )
    parser.add_argument(
        "--no-git-track",
        action="store_true",
        help=f"Do not snapshot the workspace to {GIT_TRACK_REF} ($TLAPS_NO_GIT_TRACK=1 also disables).",
    )
    parser.add_argument(
        "--shards",
        type=int,
        default=None,
        help="Parallel verification shards (tlapm --toolbox line ranges split at theorem "
        "boundaries). Default auto: single run for normal files; nproc/2, memory-capped, "
        "for huge ones. 1 forces the single-run path.",
    )
    parser.add_argument("--output", "-o", default=None, help="Write results to this file (default: <input>.result)")
    parser.add_argument(
        "--benchmark-dir",
        default=None,
        help="Canonical benchmark/<mode>/<module>/ dir (provenance oracle; defaults to git-root reconstruction)",
    )
    parser.add_argument(
        "--canonical-replay-required",
        action="store_true",
        help="Require verification with dependencies copied only from --benchmark-dir",
    )
    parser.add_argument(
        "--sany-only",
        action="store_true",
        help="Fast SANY-validity check only: parse the file with standalone "
        "tla2sany and exit (0 valid, 1 invalid) WITHOUT running tlapm. For quick "
        "syntax feedback while writing a proof — the full check applies the same gate.",
    )
    # Container vs. host. Default is auto: use the local toolchain when a tlapm
    # is installed, else fall back to Docker. These two flags force either side.
    container_group = parser.add_mutually_exclusive_group()
    container_group.add_argument(
        "--no-container",
        action="store_true",
        help="Force running tlapm on the host, never Docker (requires a local tlapm installation)",
    )
    container_group.add_argument(
        "--container",
        action="store_true",
        help="Force running inside Docker even when a local tlapm is installed",
    )
    parser.add_argument(
        "--force-build",
        action="store_true",
        help="Rebuild Docker image before running",
    )
    args = parser.parse_args()
    args.canonical_replay_required = canonical_replay_required(args.canonical_replay_required)
    if require_canonical_for_proof_from_scratch and args.mode == "proof-from-scratch":
        args.canonical_replay_required = True

    # Couple the timeout to the grader's budget: an explicit --timeout wins (the
    # grader passes it); otherwise the agent's bare `check_proof_bin <file>` picks
    # up $TLAPS_CHECK_TIMEOUT (the runner sets it to the grader's check_timeout),
    # so a proof near the time boundary can't pass the self-check yet time out at
    # grading. Falls back to 600 outside the harness.
    args.timeout = resolve_timeout(args.timeout)

    filepath = os.path.abspath(args.file)
    if not os.path.isfile(filepath):
        print(f"ERROR: File not found: {filepath}")
        sys.exit(3)

    target_name = os.path.splitext(os.path.basename(filepath))[0]
    benchmark_dir = resolve_benchmark_dir(args.benchmark_dir, filepath, target_name)
    module_unit_ids = authoritative_module_unit_ids(filepath, benchmark_dir)
    marked_task = task_has_proof_region_markers(filepath, benchmark_dir)
    marked_proof_completion = args.mode == "proof-completion" and marked_task
    strict_contract = marked_task or (args.mode == "proof-from-scratch" and args.canonical_replay_required)
    if marked_task and not args.sany_only:
        args.canonical_replay_required = True
    if args.sany_only:
        args.canonical_replay_required = False

    if not args.sany_only and benchmark_dir is not None:
        try:
            require_independent_canonical_target(filepath, benchmark_dir)
        except RuntimeError as exc:
            print(f"ERROR: {exc}")
            sys.exit(3)

    # Container vs. local: prefer the local toolchain when it is there, so a
    # native setup (and the integration tests, and a hand-run) "just works"
    # without flags; fall back to Docker only when no local tlapm is installed.
    # Already inside a container (TLAPS_IN_CONTAINER, baked into the image) → always
    # local, never nest. --no-container forces local; --container forces Docker.
    in_container = bool(os.environ.get("TLAPS_IN_CONTAINER"))
    if args.container or (not args.no_container and not in_container and find_tlapm() is None):
        _run_in_container(filepath, args)

    proof_library_catalog = None
    import_violations = []
    if args.mode == "proof-from-scratch" and strict_contract:
        catalog_path = resolve_frozen_catalog(benchmark_dir)
        try:
            proof_library_catalog = (
                load_frozen_catalog(catalog_path) if catalog_path is not None else scan_installed_libraries()
            )
            verify_installed_libraries(proof_library_catalog)
            with open(filepath, encoding="utf-8", errors="ignore") as stream:
                import_violations = validate_official_imports(
                    stream.read(),
                    proof_library_catalog.allowed_modules,
                )
        except ProofLibraryError as exc:
            print(f"ERROR: {exc}")
            sys.exit(3)

    output_path = args.output
    if output_path is None:
        output_path = os.path.splitext(filepath)[0] + ".result"

    # Fast path: --sany-only skips tlapm and just reports whether the solution
    # parses under standalone tla2sany (seconds, vs a full proof run). Same gate
    # the full check applies, so the agent can iterate on syntax quickly.
    if args.sany_only:
        if import_violations:
            for violation in import_violations:
                print(f"FAIL {violation.message} (line {violation.line})")
            sys.exit(1)
        sany_run = check_sany_valid(filepath)
        try:
            write_sany_log(sany_run, output_path)
        except OSError as exc:
            print(f"ERROR: cannot write SANY log: {exc}")
            sys.exit(3)
        status = sany_run.status.value
        detail = re.sub(r"\s+", " ", sany_run.detail).strip()
        print(f"{SANY_STATUS_PREFIX} {status}")
        if sany_run.status is SanyStatus.VALID:
            print("SANY OK — parses under standalone tla2sany")
            sys.exit(0)
        if sany_run.status is SanyStatus.INVALID:
            print(f"FAIL {SANY_INVALID_MARKER} — {detail[:300]}")
            sys.exit(1)
        print(f"ERROR: SANY validation unavailable: {detail[:300]}")
        sys.exit(3)

    # Collect all output lines, print at end and write to file
    output_lines = []

    def emit(line=""):
        output_lines.append(line)
        print(line)

    def write_result_and_exit(code):
        with open(output_path, "w") as f:
            f.write("\n".join(output_lines) + "\n")
        sys.exit(code)

    if args.canonical_replay_required and benchmark_dir is None:
        emit("ERROR: canonical replay required, but no canonical benchmark directory is available")
        write_result_and_exit(3)

    # Find tlapm
    tlapm_path = args.tlapm or find_tlapm()
    if not tlapm_path:
        emit("ERROR: tlapm not found. Use --tlapm to specify path.")
        write_result_and_exit(3)

    tlapm_lib = args.tlapm_lib or find_tlapm_lib(tlapm_path)
    if not tlapm_lib:
        emit("ERROR: tlapm lib not found. Use --tlapm-lib to specify path.")
        write_result_and_exit(3)

    # Pre-check snapshot: capture the exact state being checked; committed to
    # the hidden ref (with the verdict) at the end. Best-effort throughout.
    git_track = not (args.no_git_track or os.environ.get("TLAPS_NO_GIT_TRACK"))
    snap_repo, snap_tree = snapshot_worktree(filepath) if git_track else (None, None)
    git_track_warning = None
    if git_track and not snap_tree:
        git_track_warning = "git tracking skipped (not a git worktree or snapshot failed)"

    emit(f"Checking: {os.path.relpath(filepath)}")
    emit(f"tlapm: {tlapm_path}")
    emit(f"checker: {BUILD_VERSION}")
    if git_track_warning:
        emit(f"WARNING: {git_track_warning}")
    emit()

    if args.mode == "proof-from-scratch" and module_unit_ids is not None:
        if not module_unit_ids:
            emit("SANY-STATUS: unavailable")
            emit("ERROR: canonical module task has malformed or missing identified proof markers")
            write_result_and_exit(3)
        exit_code = run_module_task_check(
            filepath=filepath,
            benchmark_dir=benchmark_dir,
            expected_unit_ids=module_unit_ids,
            tlapm_path=tlapm_path,
            tlapm_lib=tlapm_lib,
            timeout=args.timeout,
            output_path=output_path,
            import_violations=import_violations,
            emit=emit,
        )
        write_result_and_exit(exit_code)

    # --- Step 1: Run tlapm ---
    emit("=" * 60)
    emit("TLAPM OUTPUT")
    emit("=" * 60)

    tmp_dir = tempfile.mkdtemp(prefix="tlaps_check_")
    try:
        tmp_file = stage_verification_files(
            filepath,
            tmp_dir,
            benchmark_dir=benchmark_dir,
            require_canonical=args.canonical_replay_required,
        )

        # The workspace remains the cache/provenance location. Canonical replay
        # changes only which dependency bytes enter SANY and TLAPM.
        bench_dir = os.path.dirname(filepath)

        # Static cheat phase — everything that needs no proving runs BEFORE
        # tlapm, so a detected cheat can fail fast and skip the expensive run.
        # Findings are emitted later, in the CHEATING CHECK section as always.
        cheating_issues = check_cheating(
            filepath,
            strict_preamble=(args.mode == "proof-completion" and not marked_proof_completion),
            benchmark_dir=benchmark_dir,
            require_complete_context=strict_contract,
        )
        cheating_issues.extend((violation.line, violation.message, violation.code) for violation in import_violations)
        if proof_library_catalog is not None:
            cheating_issues.extend(
                detect_official_library_shadowing(
                    filepath,
                    benchmark_dir,
                    proof_library_catalog.allowed_modules,
                )
            )
        boundary_issues = []
        if strict_contract:
            try:
                boundary_issues = check_editable_region_integrity(
                    filepath,
                    benchmark_dir,
                    proof_only=marked_proof_completion,
                )
            except RuntimeError as exc:
                emit(f"ERROR: {exc}")
                write_result_and_exit(3)
            cheating_issues.extend(boundary_issues)
        boundary_kinds = {issue[2] for issue in boundary_issues}
        real_issues = [i for i in cheating_issues if not i[1].startswith("WARNING:")]
        warnings = [i for i in cheating_issues if i[1].startswith("WARNING:")]
        legacy_vectors = legacy_gate_vectors(real_issues)

        community_lib = find_community_lib(filepath)

        summary_output = ""
        engine_issues, engine_reason, engine_result = [], "", None

        semantic_filepath = tmp_file if args.canonical_replay_required else filepath
        sany_run = check_sany_valid(semantic_filepath)
        sany_status = sany_run.status.value
        sany_detail = re.sub(r"\s+", " ", sany_run.detail).strip()
        try:
            write_sany_log(sany_run, output_path)
        except OSError as exc:
            emit(f"ERROR: cannot write SANY log: {exc}")
            write_result_and_exit(3)
        emit(f"{SANY_STATUS_PREFIX} {sany_status}")
        if sany_run.status is SanyStatus.UNAVAILABLE:
            emit(f"ERROR: SANY validation unavailable: {sany_detail[:300]}")
            write_result_and_exit(3)
        static_fail = bool(real_issues) or sany_status == "invalid"
        if args.keep_verifying or not static_fail:
            # --summary is frontend-only (no backends), but it still walks the
            # whole module. Once a static check has already failed in default
            # mode, it cannot change the verdict and can be skipped.
            summary_cmd = [tlapm_path, "-I", tlapm_lib]
            if community_lib:
                summary_cmd += ["-I", community_lib]
            summary_cmd += ["--summary", tmp_file]
            try:
                out, err, _ = run_killgroup(summary_cmd, 30, tmp_dir)
                summary_output = out + err
            except Exception:
                pass

            # tlapm has not run yet; the engine's tlapm_passed input only shapes its
            # own verdict field, which check_proof never reads (issues only).
            engine_issues, engine_reason, engine_result = run_tlacheck_engine(
                semantic_filepath,
                target_name,
                summary_output,
                False,
                benchmark_dir=benchmark_dir,
            )
            if (
                not static_fail
                and engine_result is None
                and (args.canonical_replay_required or engine_reason != "no git baseline available")
            ):
                emit(f"ERROR: semantic validation unavailable: {engine_reason or 'unknown error'}")
                write_result_and_exit(3)

        # Fail fast on tampering (cheat findings / SANY-invalid) only — an
        # honest incomplete proof still gets the full run, keeping the
        # obligation-level feedback the agent iterates on.
        cheat_found = (
            bool(real_issues) or bool(engine_result and engine_result.cheating_issues) or sany_status == "invalid"
        )
        tlapm_ran = args.keep_verifying or not cheat_found

        if tlapm_ran:
            # Shard plan: explicit --shards wins; auto only pays for unit
            # extraction (a SANY run) once the file is big enough to matter.
            with open(tmp_file) as f:
                total_lines = sum(1 for _ in f)
            try:
                shard_min = int(os.environ.get("TLAPS_SHARD_MIN_LINES", SHARD_MIN_LINES))
            except ValueError:
                shard_min = SHARD_MIN_LINES
            ranges = [(1, total_lines)]
            if (args.shards or 0) > 1 or (args.shards is None and total_lines >= shard_min):
                heads = unit_head_lines(tmp_file)
                n_shards = args.shards if args.shards is not None else auto_shard_count(len(heads))
                ranges = plan_shards(total_lines, heads, n_shards)

            if len(ranges) > 1:
                cache_root = (
                    os.path.join(bench_dir, ".tlacache") if not args.no_cache else os.path.join(tmp_dir, ".tlacache")
                )
                results = run_sharded_tlapm(
                    tlapm_path, tlapm_lib, community_lib, tmp_file, ranges, cache_root, args.timeout, tmp_dir
                )
                tlapm_output, tlapm_exit = compose_shard_results(results, target_name, args.timeout)
            else:
                # --strict makes tlapm exit non-zero on an *incomplete* proof — a step
                # with no proof (missing / OMITTED / bare QED) generates no obligation,
                # so default tlapm reports "All N obligations proved" and exits 0 even
                # though the proof is unfinished (tlaplus/tlapm#271). Exit codes: 10
                # failed obligation, 11 incomplete proof, 12 empty target. This is the
                # authoritative replacement for our hand-rolled incomplete-proof heuristics.
                cmd = [tlapm_path, "--strict", "-I", tlapm_lib]
                cmd += tlapm_cache_args(bench_dir, args.no_cache)
                if community_lib:
                    cmd += ["-I", community_lib]
                cmd.append(tmp_file)
                try:
                    out, err, rc = run_killgroup(cmd, effective_timeout(args.timeout), tmp_dir)
                    tlapm_output = out + err
                    tlapm_exit = rc
                except subprocess.TimeoutExpired:
                    tlapm_output = f"TIMEOUT after {args.timeout}s"
                    tlapm_exit = -1
                except Exception as e:
                    tlapm_output = f"ERROR: {e}"
                    tlapm_exit = -2
        else:
            tlapm_output = TLAPM_SKIP_NOTE
            tlapm_exit = None

        for line in tlapm_output.split("\n"):
            emit(line)
        # Interpret --strict: a valid solution is "complete" (all obligations
        # discharged, no MISSING step); the benchmark's GIVEN omitted lemmas do
        # not count against it. See parse_strict_status for the full rationale.
        tlapm_passed, n_missing, obligation_failed = parse_strict_status(tlapm_exit, tlapm_output)
    finally:
        shutil.rmtree(tmp_dir, ignore_errors=True)

    # --- Step 2: Cheating check ---
    emit()
    emit("=" * 60)
    emit("CHEATING CHECK")
    emit("=" * 60)

    # Check for empty PROOF blocks and 0-obligation (independent of git comparison)
    if tlapm_passed:
        with open(filepath) as f:
            cur_lines = f.read().split("\n")

        if args.mode == "proof-completion" and not marked_proof_completion:
            # proof-completion: PROOF OBVIOUS in the baseline is the boundary; slice
            # current at the same index (the preamble is required to be unchanged).
            main_content = get_baseline_text(filepath, benchmark_dir)
            if main_content:
                main_lines = main_content.split("\n")
                po_line = find_proof_obvious_line(main_lines)
                if po_line is not None:
                    proof_section = "\n".join(cur_lines[po_line:])
                    clean = strip_comments(proof_section)
                    for ci in detect_empty_proof(clean):
                        real_issues.append((po_line + (ci.line or 0), ci.description))
                    for ci in detect_zero_total_obligations(tlapm_output):
                        real_issues.append((0, ci.description))
                    for ci in detect_missing_proof(main_lines, cur_lines, po_line):
                        real_issues.append((ci.line or 0, ci.description))
        else:
            # proof-from-scratch: the agent may grow the preamble (new lemmas above target),
            # so there's no stable boundary. Scan the whole file; the bare-QED
            # check via --summary below catches what detect_missing_proof did.
            clean = strip_comments("\n".join(cur_lines))
            for ci in detect_empty_proof(clean):
                real_issues.append((ci.line or 0, ci.description))
            for ci in detect_zero_total_obligations(tlapm_output):
                real_issues.append((0, ci.description))

        # --summary missing-proofs check is shared (target theorem is still
        # the last THEOREM/LEMMA in the file for both modes).
        if summary_output:
            target_line = None
            for li, line in enumerate(cur_lines):
                if re.match(r"^(THEOREM|LEMMA|COROLLARY|PROPOSITION)\b", line.strip()):
                    target_line = li + 1  # 1-indexed
            for ci in detect_missing_proofs_summary(summary_output, target_line):
                real_issues.append((0, ci.description))

    # Semantic engine + SANY validity ran in the static phase above; fold their
    # findings in here so the report reads exactly as before.
    if engine_reason:
        warnings.append((0, f"semantic engine skipped ({engine_reason})"))
    for desc in engine_issues:
        real_issues.append((0, desc))

    for warning in warnings:
        _line_num, desc = warning[:2]
        msg = desc.removeprefix("WARNING: ")
        emit(f"  WARNING: {msg}")

    if real_issues:
        for issue in real_issues:
            line_num, desc = issue[:2]
            emit(f"  Line {line_num}: {desc}")
    else:
        emit("  No cheating detected.")

    # --- Step 3: Verdict — BINARY pass/fail via the A/B/C gate framework ------
    emit()
    emit("=" * 60)
    emit("VERDICT")
    emit("=" * 60)

    # Legacy-only signals not yet a tlacheck vector (proof-completion preamble byte-match,
    # agent-added PROOF OMITTED), computed with the same detectors the legacy
    # path uses, so the gates capture everything the old checker did.
    legacy_preamble_modified = False
    legacy_proof_omitted = False
    try:
        with open(filepath) as _f:
            _sol_text = _f.read()
        if args.mode == "proof-completion" and not marked_proof_completion:
            _main = get_baseline_text(filepath, benchmark_dir)
            if _main:
                _main_lines = _main.split("\n")
                _po = find_proof_obvious_line(_main_lines)
                if _po is not None:
                    _cur = _sol_text.split("\n")
                    legacy_preamble_modified = bool(detect_preamble_modification(_main_lines, _cur, _po))
                    legacy_proof_omitted = bool(detect_proof_omitted("\n".join(_cur[_po:])))
        else:
            legacy_proof_omitted = bool(detect_proof_omitted(_sol_text))
    except Exception:
        pass

    # The gate framework (src/tlacheck/gates.py) is the authoritative grader:
    # PASS iff identity AND discharge AND trust. "Cheating" is NOT a separate verdict
    # — it is just a gate failing, so the outcome is binary PASS / FAIL.
    # When tlapm was skipped (fail-fast) the discharge inputs are neutral: a
    # skipped run must not manufacture a "tlapm did not prove" reason — the
    # verdict already fails via the cheat and legacy_pass below.
    discharge_ok = (not obligation_failed and tlapm_exit in (0, 11)) if tlapm_ran else True
    grade_passed, grade_reasons, grade_gates, grade_cheat_checks = True, [], [], []
    try:
        from tlacheck.gates import from_tlacheck, grade

        _gr = grade(
            from_tlacheck(
                engine_result,
                tlapm_obligations_proved=discharge_ok,
                n_missing=n_missing,
                sany_valid=(sany_status == "valid"),
                preamble_modified=legacy_preamble_modified,
                proof_omitted=legacy_proof_omitted,
                scaffold_modified="SCAFFOLD_MODIFIED" in boundary_kinds,
                scaffold_format_modified="SCAFFOLD_FORMAT_MODIFIED" in boundary_kinds,
                legacy_issue_vectors=legacy_vectors,
            )
        )
        grade_passed, grade_reasons = _gr.passed, _gr.reasons
        grade_gates = [g.value for g in _gr.failed_gates()]
        # Failing integrity checks (tamper/admit) distinguish a cheat from an
        # honest incomplete proof — surfaced as a marker for the runner's report.
        grade_cheat_checks = _gr.failed_integrity_checks()
    except Exception as e:  # never let the grader crash the check
        grade_reasons = [f"gate framework unavailable ({e}); fell back to legacy verdict"]
        grade_passed = None  # signal: use legacy verdict alone

    # Safety net during migration: the legacy path must also agree before we
    # report PASS, so the consolidated grader can never be LESS strict than the
    # checker it replaces. Validated equal on a real-solution corpus; kept until
    # the legacy detectors are retired.
    legacy_pass = (not real_issues) and (sany_status == "valid") and tlapm_passed
    passed = legacy_pass if grade_passed is None else (grade_passed and legacy_pass)

    if passed:
        exit_code = 0
        emit("  PASS — target goal genuinely proved (identity and discharge and trust)")
    else:
        exit_code = 1
        emit("  FAIL")
        for reason in grade_reasons:
            emit(f"    {reason}")
        if not tlapm_ran:
            emit("    obligation checks not evaluated (tlapm skipped)")
        if sany_status == "invalid":
            emit(f"    {SANY_INVALID_MARKER} {sany_detail[:200]}")
        if grade_gates:
            emit(f"  GATES-FAILED: {','.join(grade_gates)}")
        if grade_cheat_checks:
            emit(f"  CHEAT-DETECTED: {','.join(grade_cheat_checks)}")
        if grade_passed and not legacy_pass:
            emit("  FAIL: legacy safety-net flagged a failure the gates missed — investigate divergence")

    if snap_tree:
        verdict = "PASS" if passed else "FAIL"
        commit = record_check_commit(snap_repo, snap_tree, f"check_proof {target_name} [{args.mode}]: {verdict}")
        if commit:
            emit(f"  state snapshot: {commit[:12]} (git log {GIT_TRACK_REF})")
        else:
            emit(f"  WARNING: git tracking skipped (could not update {GIT_TRACK_REF})")

    # Write result file
    print(f"\nResult written to: {output_path}")
    write_result_and_exit(exit_code)


if __name__ == "__main__":
    main()
