def require_independent_canonical_target(filepath, benchmark_dir):
    """Reject a canonical target that aliases the submitted target."""

    canonical_path = os.path.join(benchmark_dir, os.path.basename(filepath))
    try:
        aliases_submission = os.path.samefile(filepath, canonical_path)
    except FileNotFoundError:
        return
    except OSError as exc:
        raise RuntimeError(f"cannot compare submission with canonical target: {exc}") from exc
    if aliases_submission:
        raise RuntimeError("canonical benchmark target must be independent from the submitted target")


def detect_official_library_shadowing(filepath, benchmark_dir, official_modules):
    """Reject workspace files whose names override an approved official module."""

    canonical_names = set()
    if benchmark_dir:
        canonical_names = {
            os.path.splitext(os.path.basename(path))[0] for path in glob.glob(os.path.join(benchmark_dir, "*.tla"))
        }
    issues = []
    for path in glob.glob(os.path.join(os.path.dirname(filepath), "*.tla")):
        if os.path.abspath(path) == os.path.abspath(filepath):
            continue
        module_name = os.path.splitext(os.path.basename(path))[0]
        if module_name in official_modules and module_name not in canonical_names:
            issues.append(
                (
                    0,
                    f"IMPORT_SHADOWING: workspace module {module_name}.tla cannot override an official library",
                    "IMPORT_SHADOWING",
                )
            )
    return issues


def stage_verification_files(filepath, destination, *, benchmark_dir=None, require_canonical=False):
    """Stage the submitted target with the dependency source selected for grading."""

    basename = os.path.basename(filepath)
    staged_file = os.path.join(destination, basename)
    shutil.copy2(filepath, staged_file)

    if require_canonical and benchmark_dir is None:
        raise ValueError("canonical replay required, but no canonical benchmark directory is available")

    dependency_dir = benchmark_dir if require_canonical else os.path.dirname(filepath)
    for dep_file in sorted(glob.glob(os.path.join(dependency_dir, "*.tla"))):
        dep_basename = os.path.basename(dep_file)
        if dep_basename != basename:
            shutil.copy2(dep_file, os.path.join(destination, dep_basename))
    return staged_file


def check_editable_region_integrity(filepath, benchmark_dir, *, proof_only=False):
    """Return integrity failures outside a marked task's editable regions."""

    canonical_path = os.path.join(benchmark_dir, os.path.basename(filepath))
    task_kind = "proof-completion" if proof_only else "proof-from-scratch"
    parser = parse_proof_region if proof_only else parse_editable_regions
    try:
        with open(canonical_path, encoding="utf-8", newline="") as f:
            canonical_source = f.read()
    except (OSError, UnicodeError) as exc:
        raise RuntimeError(f"cannot read canonical {task_kind} task: {exc}") from exc

    try:
        canonical_regions = parser(canonical_source)
    except EditableRegionError as exc:
        raise RuntimeError(f"canonical {task_kind} task has invalid editable regions: {exc}") from exc

    try:
        with open(filepath, encoding="utf-8", newline="") as f:
            submitted_source = f.read()
    except (OSError, UnicodeError) as exc:
        return [(0, f"cannot read submitted {task_kind} task: {exc}", "SCAFFOLD_MODIFIED")]

    try:
        submitted_regions = parser(submitted_source)
    except EditableRegionError as exc:
        return [(0, f"editable-region markers were modified: {exc}", "SCAFFOLD_MODIFIED")]

    fixed_segment_status = compare_fixed_segments(canonical_regions.fixed_segments, submitted_regions.fixed_segments)
    if fixed_segment_status is FixedSegmentStatus.FORMAT_MODIFIED:
        return [
            (
                0,
                "fixed task scaffold differs only in line endings or the final newline",
                "SCAFFOLD_FORMAT_MODIFIED",
            )
        ]
    if fixed_segment_status is FixedSegmentStatus.MODIFIED:
        return [(0, "fixed task scaffold outside editable regions was modified", "SCAFFOLD_MODIFIED")]
    return []


