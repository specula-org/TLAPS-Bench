#!/usr/bin/env python3
"""
Check a single TLAPS benchmark proof for correctness and cheating.

Designed for AI agents to get quick feedback during proof writing.

Usage:
    python3 check_proof.py benchmark/Euclid/GCD_GCD3.tla \\
        [--mode {proof-completion,proof-from-scratch}] [--tlapm PATH] [--tlapm-lib PATH] \\
        [--timeout SECS] [--no-cache] [--keep-verifying] [--no-git-track] [--shards N]

Fingerprint cache:
    By default the proving run reuses <target-dir>/.tlacache.
    --no-cache verifies from scratch.

Sharding:
    Huge proofs are verified as N parallel `tlapm --strict --toolbox <s> <e>`
    ranges split at top-level theorem boundaries, with per-shard cache dirs.
    Default is auto (single run below TLAPS_SHARD_MIN_LINES lines, else
    nproc/2 capped by available memory); --shards N forces N, --shards 1
    forces the single-run path.

Fail-fast:
    Cheating is checked BEFORE proving; a detected cheat (or a SANY-invalid
    file) fails immediately and skips the tlapm run. --keep-verifying runs
    tlapm anyway.

Version tracking:
    Each run snapshots the workspace to refs/tlaps-check/history (verdict in
    the commit message, .tlacache excluded). --no-git-track or
    $TLAPS_NO_GIT_TRACK=1 disables.

Modes:
    proof-completion (default) — proof completion. Marked layered tasks allow
                  edits only inside the AGENT PROOF region and replay against
                  canonical context. Legacy unmarked tasks retain the original
                  byte-identical preamble rule.
    proof-from-scratch — proof from scratch. The agent may add new LEMMAs
                  only inside AGENT HELPERS and edits the target proof only
                  inside AGENT PROOF. Canonical context is required.

Output:
    - Raw tlapm output (preserved verbatim)
    - Cheating check (compares against main branch where applicable)
    - Binary verdict: PASS / FAIL. A cheat is not a separate verdict — it is just
      a FAIL; the failing gate is shown in the output and on a GATES-FAILED line.

Exit codes:
    0 = PASS
    1 = FAIL (proof doesn't verify, or a soundness gate failed)
    3 = ERROR (could not run check)
"""

