def _parent_pids():
    """Snapshot `pid -> ppid` for every live process.

    `/proc` where it exists — the containers and CI this runs in. Elsewhere
    (macOS has no `/proc`) fall back to `ps`, which reports the same chain:
    reading `/proc` unconditionally raised FileNotFoundError from inside
    `run_killgroup`'s timeout handler, so on a developer machine the FIRST
    tlapm timeout crashed the whole run instead of killing the escapees.
    """
    parents = {}
    if os.path.isdir("/proc"):
        for entry in os.listdir("/proc"):
            if not entry.isdigit():
                continue
            try:
                with open(f"/proc/{entry}/status") as f:
                    for line in f:
                        if line.startswith("PPid:"):
                            parents[int(entry)] = int(line.split()[1])
                            break
            except (FileNotFoundError, PermissionError, ProcessLookupError):
                continue
        return parents

    with contextlib.suppress(Exception):
        out = subprocess.run(
            ["ps", "-Ao", "pid=,ppid="], capture_output=True, text=True, timeout=30, check=False
        ).stdout
        for line in out.splitlines():
            fields = line.split()
            if len(fields) == 2 and all(f.isdigit() for f in fields):
                parents[int(fields[0])] = int(fields[1])
    return parents


def _descendant_pids(root_pid):
    """Snapshot every descendant of `root_pid` by walking PPid chains.

    Returned leaves-first so the deepest survivors die before any parent has
    a chance to fork a replacement. Robust against descendants that have
    escaped `root_pid`'s process group or session — only the PPid chain
    matters, which holds as long as we snapshot before any kills land.
    """
    parents = _parent_pids()
    children = {}
    for child, parent in parents.items():
        children.setdefault(parent, []).append(child)
    order = []
    stack = list(children.get(root_pid, []))
    while stack:
        pid = stack.pop()
        order.append(pid)
        stack.extend(children.get(pid, []))
    return list(reversed(order))


def run_killgroup(cmd, timeout, cwd):
    """Run `cmd` with a wall-clock `timeout`, killing tlapm AND every backend
    it spawned on timeout. Returns (stdout, stderr, returncode); re-raises
    subprocess.TimeoutExpired after cleanup.

    tlapm spawns its backend solvers (z3, cvc4, zenon, isabelle, ...) as
    separate processes. subprocess.run's timeout would kill only tlapm,
    orphaning the solvers — they keep running, steal CPU and tens of GB of
    RAM, and the accumulated tax stalls every later verification. We defend
    in two layers: `start_new_session=True` puts tlapm in its own process
    group and, on timeout, `killpg` SIGKILLs every member. That suffices for
    z3/cvc4/zenon (they inherit tlapm's pgid). It does NOT catch Isabelle,
    whose `bash_process` wrapper `setsid`'s into its own session — and any
    z3 spawned via the Isabelle backend rides along into that escape. So we
    additionally snapshot tlapm's PPid-chain descendants *before* killing
    (chain only holds while parents are alive) and SIGKILL each one,
    leaves-first. Covers Isabelle's polyml, isabelle.Isabelle_Tool, the
    `bash_process` wrapper, and any z3 they hold.
    """
    proc = subprocess.Popen(
        cmd,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        cwd=cwd,
        start_new_session=True,
    )
    try:
        out, err = proc.communicate(timeout=timeout)
        return out, err, proc.returncode
    except subprocess.TimeoutExpired:
        escapees = _descendant_pids(proc.pid)
        with contextlib.suppress(ProcessLookupError, PermissionError):
            os.killpg(os.getpgid(proc.pid), signal.SIGKILL)
        for pid in escapees:
            with contextlib.suppress(ProcessLookupError, PermissionError):
                os.kill(pid, signal.SIGKILL)
        with contextlib.suppress(Exception):
            proc.communicate(timeout=10)
        raise


def find_tlapm():
    """Find tlapm binary."""
    candidates = [
        "/opt/tlapm/bin/tlapm",
        os.path.expanduser("~/.tlapm/bin/tlapm"),
        "/tmp/tlapm/bin/tlapm",
        shutil.which("tlapm"),
    ]
    for candidate in candidates:
        if candidate and os.path.isfile(candidate):
            return candidate
    return None


def find_tlapm_lib(tlapm_path):
    """Derive lib path from tlapm binary path.

    tlapm 1.6 puts stdlib at lib/tlapm/stdlib; tlapm 1.5 used lib/tlaps.
    The 1.6 sub is checked first because lib/tlapm exists in 1.6 too but
    does NOT directly contain the .tla files.
    """
    configured = os.environ.get("TLAPS_LIB")
    if configured and os.path.isdir(configured):
        return configured
    base = os.path.dirname(os.path.dirname(tlapm_path))
    for sub in ["lib/tlapm/stdlib", "lib/tlaps", "lib/tlapm", "lib"]:
        path = os.path.join(base, sub)
        if os.path.isdir(path):
            return path
    return None


def find_community_lib(filepath):
    """Find vendored CommunityModules, honoring COMMUNITY_LIB before searching
    the file's git repo root and ancestor dirs. Returns the path or None.

    NOTE: this script is compiled to a standalone binary (see Makefile) and runs
    inside the agent's workspace, so unlike validate.py it can't rely on a
    repo-relative PROJECT_ROOT — it must discover lib/community/ at runtime."""
    candidates = []
    configured = os.environ.get("COMMUNITY_LIB")
    if configured:
        candidates.append(configured)
    repo_root = subprocess.run(
        ["git", "rev-parse", "--show-toplevel"],
        capture_output=True,
        text=True,
        cwd=os.path.dirname(filepath) or ".",
    ).stdout.strip()
    if repo_root:
        candidates.append(os.path.join(repo_root, "lib", "community"))
    d = os.path.dirname(os.path.abspath(filepath))
    for _ in range(6):  # walk up a few levels as a fallback
        candidates.append(os.path.join(d, "lib", "community"))
        d = os.path.dirname(d)
    for c in candidates:
        if os.path.isdir(c):
            return c
    return None


def get_main_version(filepath):
    """Get the file content from the main/master branch."""
    repo_root = subprocess.run(
        ["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True, cwd=os.path.dirname(filepath) or "."
    ).stdout.strip()

    if not repo_root:
        return None

    rel_path = os.path.relpath(filepath, repo_root)

    for branch in ["main", "master"]:
        result = subprocess.run(["git", "show", f"{branch}:{rel_path}"], capture_output=True, text=True, cwd=repo_root)
        if result.returncode == 0:
            return result.stdout

    return None


def get_baseline_text(filepath, benchmark_dir=None):
    """Canonical baseline text of ``filepath`` for the legacy detectors.

    Prefers the benchmark snapshot (``benchmark_dir/<basename>``), which the
    runner derives from canonical source files for both self-check and grading.
    In container mode the agent cannot rewrite it, so a ``git --amend`` /
    ``rm -rf .git`` in the workspace
    can no longer disguise a tampered preamble or dependency. Falls back to the
    git main/master version only when no canonical dir is available (a developer
    hand-running the checker outside the harness).
    """
    if benchmark_dir:
        cand = os.path.join(benchmark_dir, os.path.basename(filepath))
        if os.path.isfile(cand):
            try:
                with open(cand, encoding="utf-8", errors="ignore") as f:
                    return f.read()
            except (OSError, UnicodeError):
                pass
    return get_main_version(filepath)


def find_proof_obvious_line(lines):
    """Find the line number (0-indexed) of 'PROOF OBVIOUS' in the file."""
    for i in range(len(lines) - 1, -1, -1):
        if lines[i].strip() == "PROOF OBVIOUS":
            return i
    return None


def check_cheating(
    filepath,
    strict_preamble: bool = True,
    benchmark_dir=None,
    *,
    require_complete_context: bool = False,
):
    """Check for cheating by comparing against the canonical baseline.

    Args:
        strict_preamble: True for legacy proof-completion, where the preamble is
            immutable and only the proof tail may change. False for marked tasks,
            whose fixed scaffold is checked separately by editable-region
            integrity; PROOF OMITTED is then scanned across the whole file.
        benchmark_dir: canonical (tamper-proof) baseline dir; when given the
            baseline is read from there instead of workspace git (see
            get_baseline_text), so a workspace git rewrite can't fool the check.
        require_complete_context: treat every canonical sibling as a required
            dependency. Strict task snapshots contain exactly the context declared
            for one target; legacy benchmark directories may also contain unrelated
            tasks and therefore leave this disabled.

    Returns list of (line_number_1indexed, description, kind) issues.
    """
    issues = []

    # Baseline version (canonical snapshot when available, else git).
    main_content = get_baseline_text(filepath, benchmark_dir)
    if main_content is None:
        issues.append((0, "WARNING: Could not retrieve baseline version for comparison", "WARNING"))
        return issues

    main_lines = main_content.split("\n")
    with open(filepath) as f:
        current_content = f.read()
    current_lines = current_content.split("\n")

    # Find PROOF OBVIOUS in baseline version - this is the boundary
    po_line = find_proof_obvious_line(main_lines)
    if po_line is None:
        issues.append((0, "WARNING: No PROOF OBVIOUS found in baseline version", "WARNING"))
        return issues

    if strict_preamble and len(current_lines) < po_line:
        issues.append(
            (
                len(current_lines),
                f"File truncated: preamble had {po_line} lines, file has {len(current_lines)}",
                "PREAMBLE_MODIFIED",
            )
        )
        return issues

    # 1. Preamble modification — legacy proof-completion only. Marked tasks use
    # editable-region integrity instead.
    if strict_preamble:
        for ci in detect_preamble_modification(main_lines, current_lines, po_line):
            issues.append((ci.line or 0, ci.description, ci.kind))

    # 2. PROOF OMITTED / bare OMITTED.
    # Legacy proof-completion: only the proof section can plausibly contain it.
    # Marked tasks: scan the whole current file, including their editable regions.
    if strict_preamble:
        proof_section = "\n".join(current_lines[po_line:])
        for ci in detect_proof_omitted(proof_section):
            issues.append((po_line + (ci.line or 0), ci.description, ci.kind))
    else:
        for ci in detect_proof_omitted(current_content):
            issues.append((ci.line or 0, ci.description, ci.kind))

    # 3. Extra AXIOM/ASSUME (shared module)
    for ci in detect_extra_axioms(main_content, current_content):
        issues.append((0, ci.description, ci.kind))

    # 4. Dependency file modification (shared module). Baseline per dep comes
    # from the canonical snapshot (else git) — never the amendable workspace.
    bench_dir = os.path.dirname(filepath)
    dep_files = {}
    if benchmark_dir and require_complete_context:
        canonical_dependencies = sorted(glob.glob(os.path.join(benchmark_dir, "*.tla")))
        for canonical_dep in canonical_dependencies:
            basename = os.path.basename(canonical_dep)
            if basename == os.path.basename(filepath):
                continue
            workspace_dep = os.path.join(bench_dir, basename)
            if not os.path.isfile(workspace_dep):
                issues.append(
                    (0, f"Dependency file {basename} was removed or renamed — not allowed", "DEPENDENCY_MODIFIED")
                )
                continue
            try:
                with open(canonical_dep, encoding="utf-8", newline="") as f:
                    dep_baseline = f.read()
                with open(workspace_dep, encoding="utf-8", newline="") as f:
                    dep_current = f.read()
            except (OSError, UnicodeError):
                issues.append(
                    (0, f"Dependency file {basename} could not be compared — not allowed", "DEPENDENCY_MODIFIED")
                )
                continue
            dep_files[basename] = (dep_baseline, dep_current)
    else:
        for dep_file in sorted(glob.glob(os.path.join(bench_dir, "*.tla"))):
            if os.path.abspath(dep_file) == os.path.abspath(filepath):
                continue
            dep_baseline = get_baseline_text(dep_file, benchmark_dir)
            if dep_baseline is None:
                continue
            try:
                with open(dep_file, encoding="utf-8", newline="") as f:
                    dep_current = f.read()
            except (OSError, UnicodeError):
                issues.append(
                    (
                        0,
                        f"Dependency file {os.path.basename(dep_file)} could not be compared — not allowed",
                        "DEPENDENCY_MODIFIED",
                    )
                )
                continue
            dep_files[os.path.basename(dep_file)] = (dep_baseline, dep_current)

    for ci in detect_dependency_modification(dep_files):
        issues.append((0, ci.description, ci.kind))

    return issues


def legacy_gate_vectors(issues):
    vectors = set()
